// 搜索食物：内置库 + 用户自定义，按名称/别名匹配，名称前缀优先
export function searchFoods(query, customFoods = []) {
  const q = query.trim().toLowerCase();
  const all = [...customFoods.map(f => ({ ...f, custom: true })), ...FOODS];
  if (!q) return all.slice(0, 30);
  const scored = [];
  for (const f of all) {
    const name = f.n.toLowerCase();
    const aliases = (f.a || []).map(x => x.toLowerCase());
    let score = -1;
    if (name.startsWith(q)) score = 0;
    else if (name.includes(q)) score = 1;
    else if (aliases.some(x => x.startsWith(q))) score = 2;
    else if (aliases.some(x => x.includes(q))) score = 3;
    if (score >= 0) scored.push([score, f]);
  }
  scored.sort((a, b) => a[0] - b[0] || a[1].n.length - b[1].n.length);
  return scored.map(x => x[1]).slice(0, 30);
}
